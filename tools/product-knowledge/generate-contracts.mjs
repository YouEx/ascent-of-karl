#!/usr/bin/env node
import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { REPO_ROOT, validateProductContracts } from "./validate.mjs";

export const GENERATED_CONTRACT_PATH =
  "src/product/generated/contracts.ts";

function ts(value) {
  return JSON.stringify(value, null, 2);
}

export function generatedContractSource(root = REPO_ROOT) {
  const validation = validateProductContracts(root);
  if (validation.errors.length > 0) {
    throw new Error(validation.errors.join("\n"));
  }
  const {
    capabilities: manifest,
    scenarios,
    events,
    semanticUi,
  } = validation.data;
  const eventCapability = Object.fromEntries(
    events.events.map((event) => [event.id, event.capability]),
  );
  const eventScenarios = Object.fromEntries(
    events.events.map((event) => [event.id, event.scenarios]),
  );
  const actionCapability = Object.fromEntries(
    semanticUi.actions.map((action) => [action.id, action.capability]),
  );
  const scenarioState = Object.fromEntries(
    semanticUi.scenarioStates.map((entry) => [entry.scenario, entry.state]),
  );

  return `// Generated by tools/product-knowledge/generate-contracts.mjs.
// Edit docs/product/*.json, then run npm run product:generate.

export const CAPABILITY_IDS = ${ts(
    manifest.capabilities.map((capability) => capability.id),
  )} as const;
export type CapabilityId = (typeof CAPABILITY_IDS)[number];

export const SCENARIO_IDS = ${ts(
    scenarios.scenarios.map((scenario) => scenario.id),
  )} as const;
export type ScenarioId = (typeof SCENARIO_IDS)[number];

export const PRODUCT_EVENT_TYPES = ${ts(
    events.events.map((event) => event.id),
  )} as const;
export type ProductEventType = (typeof PRODUCT_EVENT_TYPES)[number];

export const ACTION_IDS = ${ts(
    semanticUi.actions.map((action) => action.id),
  )} as const;
export type ActionId = (typeof ACTION_IDS)[number];

export const UI_STATES = ${ts(semanticUi.states)} as const;
export type UiState = (typeof UI_STATES)[number];

export const EVENT_CAPABILITY = ${ts(
    eventCapability,
  )} as const satisfies Record<ProductEventType, CapabilityId>;

export const EVENT_SCENARIOS = ${ts(
    eventScenarios,
  )} as const satisfies Record<ProductEventType, readonly ScenarioId[]>;

export const ACTION_CAPABILITY = ${ts(
    actionCapability,
  )} as const satisfies Record<ActionId, CapabilityId>;

export const SCENARIO_STATE = ${ts(
    scenarioState,
  )} as const satisfies Record<ScenarioId, UiState>;

export const SEMANTIC_ATTRIBUTES = ${ts(semanticUi.attributes)} as const;
export const PRODUCT_EVENT_STORAGE_KEY = ${JSON.stringify(events.storageKey)};
export const PRODUCT_EVENT_MAX_ENTRIES = ${events.maxEntries};
`;
}

export function writeGeneratedContracts(root = REPO_ROOT) {
  const source = generatedContractSource(root);
  const output = path.join(root, GENERATED_CONTRACT_PATH);
  mkdirSync(path.dirname(output), { recursive: true });
  writeFileSync(output, source, "utf8");
  return source;
}

function isMain() {
  return (
    process.argv[1] &&
    path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
  );
}

if (isMain()) {
  try {
    const source = generatedContractSource();
    const output = path.join(REPO_ROOT, GENERATED_CONTRACT_PATH);
    if (process.argv.includes("--check")) {
      if (!existsSync(output) || readFileSync(output, "utf8") !== source) {
        throw new Error(
          `${GENERATED_CONTRACT_PATH} is stale; run npm run product:generate`,
        );
      }
      console.log("Generated product TypeScript contracts are current.");
    } else {
      writeGeneratedContracts();
      console.log(`Wrote ${GENERATED_CONTRACT_PATH}.`);
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
